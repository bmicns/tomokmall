    if (isset(CATALOG_DAC_STD_EXCEPTIONS[$vendorSlug])) { return CATALOG_DAC_STD_EXCEPTIONS[$vendorSlug]; }   // '' = 반영 안 함
    return preg_match('/^dac-(\d+)$/', $vendorSlug, $m) ? 'ktomok-' . $m[1] : null;
}
