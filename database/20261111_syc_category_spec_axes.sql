-- 목적: 상용콘크리트 품목(syc_categories)마다 규격 칸(syc_products.dim_* 등)의 이름·약자·단위·표시 위치를 정한다.
--       사이트 목록 표는 '규격' 머리글 아래 이 이름표대로 칸을 나누고(in_list=1), 상세 화면은 값이 있는 모든 칸을 이 이름으로 보인다.
--       기존 category_spec_axes(케이토목 products 용)는 바꾸지 않는다 — 사용자 결정 2026-11-11.
-- 키(axis_key): syc_products 칸 이름에서 'dim_' 를 뗀 것(w·w_o·t_top·l1 …), 철선 품번은 wire_no(= spec_wire_no). 코드(app/syc_catalog.php)가 허용 목록으로 확인.
-- 초안 원천: docs/02-design/syc-products.md 2장 대응표 + data/syccrt/products.json 에 값이 있는 칸(2026-11-11).
--   use_filter: 목록 표 칸 중 지금 데이터의 서로 다른 값이 2~20개인 칸만 1(실제 데이터를 받으면 다시 정함).
-- 사용 코드: app/syc_catalog.php · public/syc-products.php · public/syc-product.php (관리자 '상용콘크리트로 보기' 미리보기에서만)
-- 성격: 추가형(새 표 1개 + 행). 가격 칸 없음. 선행: database/20261110_syc_categories.sql
-- 행 수: 392 (품목 69개). 다시 실행해도 중복 없음(품목·키 기준).
-- 실행: 사용자 승인 후. 되돌리기: DROP TABLE syc_category_spec_axes;

CREATE TABLE IF NOT EXISTS syc_category_spec_axes (
    id          INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    category_id INT UNSIGNED NOT NULL                 COMMENT 'syc_categories.id(품목)',
    seq         TINYINT UNSIGNED NOT NULL             COMMENT '표시 순서(1부터)',
    axis_key    VARCHAR(20) NOT NULL                  COMMENT 'syc_products 칸(dim_ 뗀 이름, wire_no = spec_wire_no)',
    label       VARCHAR(20) NOT NULL                  COMMENT '화면 이름(예: 폭, 내공폭, 상판두께)',
    symbol      VARCHAR(4)  NULL                      COMMENT '약자(예: W, Bo, T1) — 없으면 이름만',
    unit        ENUM('mm','m','no','t/m') NOT NULL DEFAULT 'mm' COMMENT '표시 단위(저장은 mm, no = 번호 #10)',
    in_list     TINYINT(1) NOT NULL DEFAULT 1         COMMENT '목록 표에 칸으로 보이기(0 = 상세 화면에만)',
    use_filter  TINYINT(1) NOT NULL DEFAULT 0         COMMENT '목록 왼쪽 필터에 보이기',
    is_active   TINYINT(1) NOT NULL DEFAULT 1,
    updated_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uq_sycax_key (category_id, axis_key),
    UNIQUE KEY uq_sycax_seq (category_id, seq),
    CONSTRAINT fk_sycax_category FOREIGN KEY (category_id) REFERENCES syc_categories(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='상용콘크리트 품목별 규격 칸 이름표 — category_spec_axes 와 별개';

