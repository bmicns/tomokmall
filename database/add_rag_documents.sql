CREATE TABLE IF NOT EXISTS rag_documents (
    id           INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    title        VARCHAR(200) NOT NULL COMMENT '문서 제목',
    content      TEXT         NOT NULL COMMENT '문서 본문 (AI 프롬프트에 주입)',
    category_key VARCHAR(50)  NULL     COMMENT 'grating/pe_pipe/manhole/culvert/pavement — NULL이면 공통',
    tags         VARCHAR(500) NULL     COMMENT '추가 검색 키워드 (콤마 구분)',
    is_active    TINYINT(1)   NOT NULL DEFAULT 1,
    sort_order   INT          NOT NULL DEFAULT 0,
    created_at   DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FULLTEXT idx_ft (title, content, tags)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

